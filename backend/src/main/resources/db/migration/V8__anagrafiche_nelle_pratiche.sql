-- Schede di anagrafica collegate alle pratiche da un campo "anagrafica" di un form, con la fotografia dei dati
-- al momento del collegamento (quello che si è deciso resta legato ai dati di allora).

CREATE TABLE pratica_anagrafica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id VARCHAR(64) NOT NULL,
    campo VARCHAR(100) NOT NULL,
    scheda_id BIGINT NOT NULL,
    versione_scheda BIGINT NOT NULL,
    titolo VARCHAR(500) NOT NULL,
    fotografia TEXT NOT NULL,
    collegata_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    collegata_da VARCHAR(100),
    CONSTRAINT pk_pratica_anagrafica PRIMARY KEY (id),
    CONSTRAINT uk_pratica_anagrafica_campo UNIQUE (process_instance_id, campo),
    CONSTRAINT fk_pratica_anagrafica_scheda FOREIGN KEY (scheda_id) REFERENCES anagrafica_scheda (id)
);
CREATE INDEX ix_pratica_anagrafica_scheda ON pratica_anagrafica (scheda_id);
