-- Registro delle letture (chi ha aperto quale pratica, attività, documento o scheda) e degli errori imprevisti
-- (richieste finite in errore 500 e lavori del motore falliti). Tabelle separate dal registro delle azioni perché
-- crescono molto di più: si conservano per un periodo configurabile (app.registro.*-giorni).

CREATE TABLE registro_lettura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    quando TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    utente VARCHAR(100),
    azione VARCHAR(40) NOT NULL,
    oggetto VARCHAR(255),
    dettagli VARCHAR(500),
    esito VARCHAR(20) NOT NULL,
    indirizzo VARCHAR(64),
    CONSTRAINT pk_registro_lettura PRIMARY KEY (id)
);
CREATE INDEX ix_registro_lettura_quando ON registro_lettura (quando);
CREATE INDEX ix_registro_lettura_oggetto ON registro_lettura (oggetto);
CREATE INDEX ix_registro_lettura_utente ON registro_lettura (utente);

CREATE TABLE registro_errore (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    quando TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    codice VARCHAR(20) NOT NULL,
    origine VARCHAR(20) NOT NULL,
    utente VARCHAR(100),
    richiesta VARCHAR(500),
    tipo VARCHAR(255),
    messaggio TEXT,
    traccia TEXT,
    indirizzo VARCHAR(64),
    CONSTRAINT pk_registro_errore PRIMARY KEY (id),
    CONSTRAINT uk_registro_errore_codice UNIQUE (codice)
);
CREATE INDEX ix_registro_errore_quando ON registro_errore (quando);
