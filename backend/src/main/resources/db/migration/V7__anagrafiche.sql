-- Anagrafiche configurabili: tipi definiti dall'analista (campi come nei form), schede con i dati, indice per la
-- ricerca e per i campi chiave, versioni di ogni modifica e permessi per tipo (vede, modifica, esporta).
-- Le schede non si cancellano: si cessano, così le pratiche che le citano restano coerenti.

CREATE TABLE anagrafica_tipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codice VARCHAR(60) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    descrizione VARCHAR(1000),
    definizione TEXT NOT NULL,
    versione INTEGER NOT NULL,
    attivo BOOLEAN NOT NULL,
    creato_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creato_da VARCHAR(100),
    modificato_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificato_da VARCHAR(100),
    CONSTRAINT pk_anagrafica_tipo PRIMARY KEY (id),
    CONSTRAINT uk_anagrafica_tipo_codice UNIQUE (codice)
);

CREATE TABLE anagrafica_scheda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_id BIGINT NOT NULL,
    titolo VARCHAR(500) NOT NULL,
    dati TEXT NOT NULL,
    stato VARCHAR(20) NOT NULL,
    versione BIGINT NOT NULL,
    creata_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creata_da VARCHAR(100),
    modificata_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificata_da VARCHAR(100),
    CONSTRAINT pk_anagrafica_scheda PRIMARY KEY (id),
    CONSTRAINT fk_anagrafica_scheda_tipo FOREIGN KEY (tipo_id) REFERENCES anagrafica_tipo (id)
);
CREATE INDEX ix_anagrafica_scheda_tipo ON anagrafica_scheda (tipo_id, stato, titolo);

-- valori dei campi chiave, ricercabili e delle relazioni; "chiave" è valorizzata solo per i campi chiave,
-- così il vincolo UNIQUE vale solo per loro (più NULL sono ammessi su PostgreSQL e H2)
CREATE TABLE anagrafica_indice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scheda_id BIGINT NOT NULL,
    tipo_id BIGINT NOT NULL,
    campo VARCHAR(100) NOT NULL,
    valore VARCHAR(255) NOT NULL,
    chiave VARCHAR(255),
    CONSTRAINT pk_anagrafica_indice PRIMARY KEY (id),
    CONSTRAINT fk_anagrafica_indice_scheda FOREIGN KEY (scheda_id) REFERENCES anagrafica_scheda (id) ON DELETE CASCADE,
    CONSTRAINT fk_anagrafica_indice_tipo FOREIGN KEY (tipo_id) REFERENCES anagrafica_tipo (id),
    CONSTRAINT uk_anagrafica_indice_chiave UNIQUE (tipo_id, campo, chiave)
);
CREATE INDEX ix_anagrafica_indice_valore ON anagrafica_indice (tipo_id, valore);
CREATE INDEX ix_anagrafica_indice_scheda ON anagrafica_indice (scheda_id);

CREATE TABLE anagrafica_versione (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scheda_id BIGINT NOT NULL,
    numero BIGINT NOT NULL,
    operazione VARCHAR(20) NOT NULL,
    dati TEXT NOT NULL,
    stato VARCHAR(20) NOT NULL,
    versione_tipo INTEGER NOT NULL,
    il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    utente VARCHAR(100),
    nota VARCHAR(1000),
    CONSTRAINT pk_anagrafica_versione PRIMARY KEY (id),
    CONSTRAINT fk_anagrafica_versione_scheda FOREIGN KEY (scheda_id) REFERENCES anagrafica_scheda (id),
    CONSTRAINT uk_anagrafica_versione UNIQUE (scheda_id, numero)
);

CREATE TABLE permesso_anagrafica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_id BIGINT NOT NULL,
    azione VARCHAR(20) NOT NULL,
    tipo_soggetto VARCHAR(20) NOT NULL,
    soggetto VARCHAR(100) NOT NULL,
    CONSTRAINT pk_permesso_anagrafica PRIMARY KEY (id),
    CONSTRAINT fk_permesso_anagrafica_tipo FOREIGN KEY (tipo_id) REFERENCES anagrafica_tipo (id),
    CONSTRAINT uk_permesso_anagrafica UNIQUE (tipo_id, azione, tipo_soggetto, soggetto)
);
CREATE INDEX ix_permesso_anagrafica_soggetto ON permesso_anagrafica (tipo_soggetto, soggetto);

-- l'analista definisce anche i tipi di anagrafica
INSERT INTO ruolo_permesso (ruolo_id, permesso) SELECT id, 'anagrafiche.definisci' FROM ruolo WHERE codice = 'analista';
