-- Versioni dei form: ogni salvataggio nello Studio aggiunge una versione, e ogni pratica resta sulle versioni dei
-- form che c'erano quando è stata avviata. Così un form cambiato vale per le pratiche nuove e non sorprende quelle
-- in corso (campi obbligatori nuovi, campi tolti).

ALTER TABLE form_definition ADD COLUMN versione INTEGER DEFAULT 1 NOT NULL;

CREATE TABLE form_versione (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    form_key VARCHAR(200) NOT NULL,
    versione INTEGER NOT NULL,
    json TEXT NOT NULL,
    salvato_il TIMESTAMP(6) WITH TIME ZONE,
    salvato_da VARCHAR(255),
    CONSTRAINT pk_form_versione PRIMARY KEY (id),
    CONSTRAINT uk_form_versione UNIQUE (form_key, versione)
);

-- i form già salvati diventano la versione 1
INSERT INTO form_versione (form_key, versione, json, salvato_il, salvato_da)
    SELECT form_key, 1, json, updated_at, updated_by FROM form_definition;

-- la versione di ogni form usata da una pratica (fissata all'avvio)
CREATE TABLE pratica_form (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id VARCHAR(64) NOT NULL,
    form_key VARCHAR(200) NOT NULL,
    versione INTEGER NOT NULL,
    CONSTRAINT pk_pratica_form PRIMARY KEY (id),
    CONSTRAINT uk_pratica_form UNIQUE (process_instance_id, form_key)
);
