-- Ruoli applicativi: insiemi di permessi assegnabili a utenti e gruppi (anche gruppi del provider OIDC).
-- Prende il posto della colonna app_user.admin: chi era amministratore riceve il ruolo "amministratore".

CREATE TABLE ruolo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codice VARCHAR(60) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descrizione TEXT,
    predefinito BOOLEAN NOT NULL,
    CONSTRAINT pk_ruolo PRIMARY KEY (id),
    CONSTRAINT uk_ruolo_codice UNIQUE (codice)
);

CREATE TABLE ruolo_permesso (
    ruolo_id BIGINT NOT NULL,
    permesso VARCHAR(60) NOT NULL,
    CONSTRAINT pk_ruolo_permesso PRIMARY KEY (ruolo_id, permesso),
    CONSTRAINT fk_ruolo_permesso_ruolo FOREIGN KEY (ruolo_id) REFERENCES ruolo (id) ON DELETE CASCADE
);

CREATE TABLE ruolo_gruppo (
    ruolo_id BIGINT NOT NULL,
    gruppo VARCHAR(100) NOT NULL,
    CONSTRAINT pk_ruolo_gruppo PRIMARY KEY (ruolo_id, gruppo),
    CONSTRAINT fk_ruolo_gruppo_ruolo FOREIGN KEY (ruolo_id) REFERENCES ruolo (id) ON DELETE CASCADE
);
CREATE INDEX ix_ruolo_gruppo_gruppo ON ruolo_gruppo (gruppo);

CREATE TABLE app_user_ruolo (
    user_id BIGINT NOT NULL,
    ruolo_id BIGINT NOT NULL,
    CONSTRAINT pk_app_user_ruolo PRIMARY KEY (user_id, ruolo_id),
    CONSTRAINT fk_app_user_ruolo_utente FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_app_user_ruolo_ruolo FOREIGN KEY (ruolo_id) REFERENCES ruolo (id) ON DELETE CASCADE
);
CREATE INDEX ix_app_user_ruolo_ruolo ON app_user_ruolo (ruolo_id);

