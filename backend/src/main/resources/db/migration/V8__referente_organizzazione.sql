-- Referenti delle organizzazioni esterne: gestiscono da soli le persone della loro organizzazione.
-- Più: password temporanea da cambiare al primo accesso, chi ha creato l'utente e quando, ultimo accesso.

CREATE TABLE organizzazione_referente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    organizzazione_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    nominato_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nominato_da VARCHAR(100),
    CONSTRAINT pk_organizzazione_referente PRIMARY KEY (id),
    CONSTRAINT uk_organizzazione_referente UNIQUE (organizzazione_id, user_id),
    CONSTRAINT fk_referente_org FOREIGN KEY (organizzazione_id) REFERENCES organizzazione (id) ON DELETE CASCADE,
    CONSTRAINT fk_referente_utente FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX ix_referente_utente ON organizzazione_referente (user_id);

ALTER TABLE app_user ADD COLUMN password_temporanea BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE app_user ADD COLUMN creato_da VARCHAR(100);
ALTER TABLE app_user ADD COLUMN creato_il TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE app_user ADD COLUMN ultimo_accesso TIMESTAMP(6) WITH TIME ZONE;
