-- Schema delle tabelle di Orditogram alla versione 0.12, prima di Flyway.
-- Le tabelle di Activiti (ACT_*) non stanno qui: le crea e aggiorna il motore.
--
-- "IF NOT EXISTS" ovunque: su un database creato da Orditogram 0.12 con ddl-auto (tabelle già presenti)
-- questo script non cambia nulla e Flyway inizia a tenere traccia delle migrazioni da qui in poi.
-- Lo script gira uguale su PostgreSQL e su H2 (test).

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    admin BOOLEAN NOT NULL,
    email VARCHAR(255),
    enabled BOOLEAN NOT NULL,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    oidc_soggetto VARCHAR(500),
    password VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL,
    CONSTRAINT app_user_pkey PRIMARY KEY (id),
    CONSTRAINT uk3k4cplvh82srueuttfkwnylq0 UNIQUE (username),
    CONSTRAINT uk7i2q9ixh0sjmke0wb9vletiy1 UNIQUE (oidc_soggetto)
);

CREATE TABLE IF NOT EXISTS app_user_group (
    user_id BIGINT NOT NULL,
    group_name VARCHAR(100),
    CONSTRAINT fk6u1uxwt4dn71l0xg0mr60pify FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE IF NOT EXISTS chiave_api (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ambiti VARCHAR(500) NOT NULL,
    attiva BOOLEAN NOT NULL,
    creata TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creata_da VARCHAR(100),
    descrizione VARCHAR(255),
    impronta VARCHAR(64) NOT NULL,
    nome VARCHAR(60) NOT NULL,
    prefisso VARCHAR(20) NOT NULL,
    processi VARCHAR(2000),
    revocata TIMESTAMP(6) WITH TIME ZONE,
    scadenza DATE,
    ultimo_indirizzo VARCHAR(64),
    ultimo_uso TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT chiave_api_pkey PRIMARY KEY (id),
    CONSTRAINT uk509jdey57p6bpt47c35a9l8g0 UNIQUE (nome)
);
CREATE INDEX IF NOT EXISTS ix_chiave_api_prefisso ON chiave_api (prefisso);

CREATE TABLE IF NOT EXISTS webhook (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attivo BOOLEAN NOT NULL,
    creato TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creato_da VARCHAR(100),
    descrizione VARCHAR(255),
    eventi VARCHAR(1000),
    nome VARCHAR(80) NOT NULL,
    processi VARCHAR(2000),
    segreto VARCHAR(500) NOT NULL,
    url VARCHAR(1000) NOT NULL,
    CONSTRAINT webhook_pkey PRIMARY KEY (id),
    CONSTRAINT ukpml7lp2ihtfrh0amb6dg4kqu6 UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS consegna_webhook (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codice_risposta INTEGER,
    creata TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    durata_ms BIGINT,
    errore VARCHAR(1000),
    evento_id VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    pratica VARCHAR(64),
    prossimo_tentativo TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    risposta VARCHAR(2000),
    stato VARCHAR(20) NOT NULL,
    tentativi INTEGER NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    ultimo_tentativo TIMESTAMP(6) WITH TIME ZONE,
    webhook_id BIGINT NOT NULL,
    CONSTRAINT consegna_webhook_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_consegna_coda ON consegna_webhook (stato, prossimo_tentativo);
CREATE INDEX IF NOT EXISTS ix_consegna_webhook ON consegna_webhook (webhook_id, id);

CREATE TABLE IF NOT EXISTS documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    creato_da VARCHAR(255),
    creato_il TIMESTAMP(6) WITH TIME ZONE,
    nome VARCHAR(255) NOT NULL,
    process_instance_id VARCHAR(64) NOT NULL,
    versione_corrente INTEGER NOT NULL,
    CONSTRAINT documento_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_documento_pratica ON documento (process_instance_id);

CREATE TABLE IF NOT EXISTS documento_versione (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    caricato_da VARCHAR(255),
    caricato_da_nome VARCHAR(255),
    caricato_il TIMESTAMP(6) WITH TIME ZONE,
    content_type VARCHAR(255),
    dimensione BIGINT NOT NULL,
    fase VARCHAR(255),
    filename VARCHAR(255) NOT NULL,
    firma_esito VARCHAR(20),
    firma_report TEXT,
    firma_tipo VARCHAR(20),
    nota TEXT,
    numero INTEGER NOT NULL,
    percorso VARCHAR(255) NOT NULL,
    sha256 VARCHAR(64),
    documento_id BIGINT NOT NULL,
    CONSTRAINT documento_versione_pkey PRIMARY KEY (id),
    CONSTRAINT fk77ijfedxvok9wru9u88v1u179 FOREIGN KEY (documento_id) REFERENCES documento (id)
);

CREATE TABLE IF NOT EXISTS form_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    form_key VARCHAR(200) NOT NULL,
    json TEXT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    updated_by VARCHAR(255),
    CONSTRAINT form_definition_pkey PRIMARY KEY (id),
    CONSTRAINT ukeerpb9vujaxtvpn1jqhq37jqg UNIQUE (form_key)
);

CREATE TABLE IF NOT EXISTS notifica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    creata_il TIMESTAMP(6) WITH TIME ZONE,
    letta BOOLEAN NOT NULL,
    messaggio TEXT,
    process_instance_id VARCHAR(64),
    titolo VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL,
    CONSTRAINT notifica_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_notifica_utente ON notifica (username, letta);

-- tipo senza vincolo CHECK: i valori ammessi li controlla l'applicazione (vedi V2)
CREATE TABLE IF NOT EXISTS pratica_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dettagli TEXT,
    process_instance_id VARCHAR(64) NOT NULL,
    quando TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    titolo VARCHAR(255),
    utente VARCHAR(100),
    utente_nome VARCHAR(255),
    CONSTRAINT pratica_evento_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_evento_pratica ON pratica_evento (process_instance_id);
CREATE INDEX IF NOT EXISTS ix_evento_utente ON pratica_evento (utente);

CREATE TABLE IF NOT EXISTS processo_bozza (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    aggiornato_da VARCHAR(255),
    aggiornato_il TIMESTAMP(6) WITH TIME ZONE,
    chiave VARCHAR(200) NOT NULL,
    nome VARCHAR(255),
    xml TEXT NOT NULL,
    CONSTRAINT processo_bozza_pkey PRIMARY KEY (id),
    CONSTRAINT ukmf3624vuny15rnjwsdicugl79 UNIQUE (chiave)
);

CREATE TABLE IF NOT EXISTS registro_azione (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    azione VARCHAR(40) NOT NULL,
    dettagli TEXT,
    indirizzo VARCHAR(64),
    oggetto VARCHAR(255),
    quando TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    utente VARCHAR(100),
    utente_nome VARCHAR(255),
    CONSTRAINT registro_azione_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_registro_azione ON registro_azione (azione);
CREATE INDEX IF NOT EXISTS ix_registro_quando ON registro_azione (quando);
CREATE INDEX IF NOT EXISTS ix_registro_utente ON registro_azione (utente);
