-- Strutture dell'ente in un albero, utenti nelle strutture, struttura competente delle pratiche
-- e permessi per processo (avviare, vedere tutte le pratiche entro un ambito, esportare).

CREATE TABLE organizzazione (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codice VARCHAR(60) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    codice_fiscale VARCHAR(20),
    tipo VARCHAR(20) NOT NULL,
    padre_id BIGINT,
    attiva BOOLEAN NOT NULL,
    CONSTRAINT pk_organizzazione PRIMARY KEY (id),
    CONSTRAINT uk_organizzazione_codice UNIQUE (codice),
    CONSTRAINT fk_organizzazione_padre FOREIGN KEY (padre_id) REFERENCES organizzazione (id)
);
CREATE INDEX ix_organizzazione_padre ON organizzazione (padre_id);

CREATE TABLE app_user_organizzazione (
    user_id BIGINT NOT NULL,
    organizzazione_id BIGINT NOT NULL,
    CONSTRAINT pk_app_user_organizzazione PRIMARY KEY (user_id, organizzazione_id),
    CONSTRAINT fk_app_user_org_utente FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_app_user_org_org FOREIGN KEY (organizzazione_id) REFERENCES organizzazione (id) ON DELETE CASCADE
);
CREATE INDEX ix_app_user_org_org ON app_user_organizzazione (organizzazione_id);

CREATE TABLE pratica_struttura (
    process_instance_id VARCHAR(64) NOT NULL,
    organizzazione_id BIGINT NOT NULL,
    CONSTRAINT pk_pratica_struttura PRIMARY KEY (process_instance_id),
    CONSTRAINT fk_pratica_struttura_org FOREIGN KEY (organizzazione_id) REFERENCES organizzazione (id)
);
CREATE INDEX ix_pratica_struttura_org ON pratica_struttura (organizzazione_id);

CREATE TABLE permesso_processo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    processo VARCHAR(255) NOT NULL,
    azione VARCHAR(20) NOT NULL,
    tipo_soggetto VARCHAR(20) NOT NULL,
    soggetto VARCHAR(100) NOT NULL,
    ambito VARCHAR(30) NOT NULL,
    CONSTRAINT pk_permesso_processo PRIMARY KEY (id),
    CONSTRAINT uk_permesso_processo UNIQUE (processo, azione, tipo_soggetto, soggetto)
);
CREATE INDEX ix_permesso_processo_azione ON permesso_processo (azione, tipo_soggetto, soggetto);

-- l'elenco delle pratiche cerca nello storico per utente
CREATE INDEX IF NOT EXISTS ix_evento_utente_pratica ON pratica_evento (utente, process_instance_id);
