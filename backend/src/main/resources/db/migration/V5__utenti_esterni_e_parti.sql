-- Utenti esterni (cittadini, clienti, referenti di enti e aziende), organizzazioni esterne, parti della pratica
-- e visibilità dei documenti. Gli utenti e i documenti esistenti restano interni.

ALTER TABLE app_user ADD COLUMN tipo VARCHAR(20) DEFAULT 'INTERNO' NOT NULL;

ALTER TABLE documento ADD COLUMN visibilita VARCHAR(20) DEFAULT 'INTERNA' NOT NULL;

CREATE TABLE pratica_parte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id VARCHAR(64) NOT NULL,
    ruolo VARCHAR(60) NOT NULL,
    utente VARCHAR(100),
    organizzazione_id BIGINT,
    aggiunta_il TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    aggiunta_da VARCHAR(100),
    CONSTRAINT pk_pratica_parte PRIMARY KEY (id),
    CONSTRAINT uk_pratica_parte_ruolo UNIQUE (process_instance_id, ruolo),
    CONSTRAINT fk_pratica_parte_org FOREIGN KEY (organizzazione_id) REFERENCES organizzazione (id)
);
CREATE INDEX ix_pratica_parte_utente ON pratica_parte (utente);
CREATE INDEX ix_pratica_parte_org ON pratica_parte (organizzazione_id);

-- chi gestisce gli utenti gestisce anche le organizzazioni esterne
INSERT INTO ruolo_permesso (ruolo_id, permesso) SELECT id, 'organizzazioni.gestisci' FROM ruolo WHERE codice = 'gestore-utenti';
